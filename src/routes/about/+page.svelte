	<h1 class="mb-3 font-lexend text-[2.2rem]">Who Are We?</h1>
	<p class="max-w-reading text-center font-pt text-[1.18rem]">
		Echoes of Eden is a nascent creative arts ministry based in Manhattan, KS, whose aim is to
		proclaim God's glory through the cultivation and enjoyment of art and media. In essence, we are
		a group of creative Christian book and music nerds who love learning about the God of the Bible
		through creative arts (stories, poems, songs, drawings, etc.), and we want to share that with
		others. We hope to grow and invest in creative communities by hosting events, providing
		resources, and giving artists a platform to share their creations. We are very, very early in
		this project, but we eventually plan to become a non-profit organization and use this website as
		a central platform to share our and others' creations. We have many dreams and aspirations for
		this, but trust that however it goes (whether it grows or goes away) God will use it well. Keep
		checking back on this website for updates on what we're doing!
	</p>

	<h1 class="mt-10 mb-3 font-lexend text-[2.2rem]">Theology of Art</h1>
	<p class="max-w-reading text-center font-pt text-[1.18rem]">
		One of our most immediate goals is getting down a theology of art. How should we use and think
		about art? Is all art good? What is the purpose of art? Our goal is to study what God says in
		the Bible about all this, and eventually write down a summary and explanation of it all. For now
		however, suffice it to say that we think art in general is good, and its purpose is to glorify
		God in large part by simply enjoying it.
	</p>
